-- Timeline entries shown on the public status page: automatic lifecycle events
-- (first reports, confirmed, resolved) and updates posted by operators.

CREATE TABLE incident_update (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT                   NOT NULL REFERENCES incident (id),
    kind        VARCHAR(16)              NOT NULL,
    title       VARCHAR(120)             NOT NULL,
    body        VARCHAR(1000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_update_incident ON incident_update (incident_id, created_at);
