-- Portable between PostgreSQL and H2 (MODE=PostgreSQL).

CREATE TABLE incident (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_type      VARCHAR(16)              NOT NULL,
    status            VARCHAR(16)              NOT NULL,
    centroid_lat      DOUBLE PRECISION         NOT NULL,
    centroid_lng      DOUBLE PRECISION         NOT NULL,
    radius_km         DOUBLE PRECISION         NOT NULL,
    report_count      INTEGER                  NOT NULL,
    first_reported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_reported_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at      TIMESTAMP WITH TIME ZONE,
    resolved_at       TIMESTAMP WITH TIME ZONE,
    resolution_note   VARCHAR(500),
    version           BIGINT                   NOT NULL DEFAULT 0
);

CREATE INDEX idx_incident_type_status ON incident (service_type, status);
CREATE INDEX idx_incident_status_last ON incident (status, last_reported_at);

CREATE TABLE outage_report (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_type VARCHAR(16)              NOT NULL,
    latitude     DOUBLE PRECISION         NOT NULL,
    longitude    DOUBLE PRECISION         NOT NULL,
    zip_code     VARCHAR(10),
    description  VARCHAR(500),
    reported_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    client_hash  VARCHAR(64)              NOT NULL,
    incident_id  BIGINT REFERENCES incident (id)
);

-- Supports the "recent unclustered reports of this type" pre-filter.
CREATE INDEX idx_report_type_time ON outage_report (service_type, reported_at);
CREATE INDEX idx_report_lat_lng ON outage_report (latitude, longitude);
CREATE INDEX idx_report_incident ON outage_report (incident_id, reported_at);
CREATE INDEX idx_report_client ON outage_report (client_hash, service_type, reported_at);

CREATE TABLE subscription (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             VARCHAR(254)             NOT NULL,
    latitude          DOUBLE PRECISION         NOT NULL,
    longitude         DOUBLE PRECISION         NOT NULL,
    radius_km         DOUBLE PRECISION         NOT NULL,
    service_type      VARCHAR(16),
    webhook_url       VARCHAR(500),
    unsubscribe_token VARCHAR(36)              NOT NULL UNIQUE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_subscription_type ON subscription (service_type);
